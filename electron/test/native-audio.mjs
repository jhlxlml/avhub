import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {audioOutputStatus,audioOutputFailure}=require('../dist/nativeAudio.js');
const {MpvClient}=require('../dist/mpvClient.js');
for(const invalid of [null,undefined,{},[{}],[{name:''}],[{name:2}]])assert.deepEqual(audioOutputStatus(invalid),{state:'unknown',availableCount:null});
for(const empty of [[],[{name:'auto',description:'Autoselect device'}]])assert.deepEqual(audioOutputStatus(empty),{state:'unavailable',availableCount:0});
const raw=[{name:'auto'},{name:'wasapi/private-endpoint-id',description:'personal speaker'},{name:'wasapi/private-endpoint-id'}];
assert.deepEqual(audioOutputStatus(raw),{state:'available',availableCount:1});
const published=[],commands=[],client=new MpvClient(value=>published.push(value),()=>{});
client.command=async command=>{commands.push(command);return null;};
client.message({event:'start-file'});client.message({event:'file-loaded'});
assert.equal(commands.length,0,'healthy startup does not enumerate or observe devices');
client.message({event:'end-file',reason:'error',file_error:'audio output initialization failed'});
assert.equal(commands.filter(c=>c[0]==='observe_property'&&c[2]==='audio-device-list').length,1);
client.message({event:'property-change',name:'audio-device-list',data:[{name:'auto'}]});
assert.match(client.snapshot.error,/当前会话未检测到/);assert.equal(client.snapshot.phase,'error');
client.message({event:'property-change',name:'audio-device-list',data:raw});
assert.match(client.snapshot.error,/已检测到声音输出设备/);assert.equal(client.snapshot.phase,'error','device arrival never auto-restarts playback');
assert.equal(client.snapshot.sourceLoads,1);assert.equal(client.snapshot.readyMs,null);
assert.doesNotMatch(JSON.stringify(published),/private-endpoint|personal speaker|wasapi\//,'device identities never leave the decoder');
assert.equal(Object.hasOwn(client.snapshot.properties,'audio-device-list'),false);
client.message({event:'end-file',reason:'error',file_error:'audio output initialization failed'});
assert.equal(commands.length,1,'one observer, not a retry/poll loop or an audio-device write');
assert.throws(()=>client.seek(5),/重新打开/);
await client.stop();client.message({event:'property-change',name:'audio-device-list',data:[]});
assert.equal(client.snapshot.audioOutput.state,'available','late device changes cannot revive a stopped client');
const unavailable=new MpvClient(()=>{},()=>{});
unavailable.command=async()=>{throw new Error('disconnected transport');};
unavailable.message({event:'end-file',reason:'error',file_error:'audio output initialization failed'});
await new Promise(resolve=>setTimeout(resolve,0));assert.match(unavailable.snapshot.error,/请检查 Windows/);assert.equal(unavailable.snapshot.phase,'error');await unavailable.stop();
assert.match(audioOutputFailure({state:'unknown',availableCount:null}),/未自动静音或转换音频/);
console.log('Native audio availability passed: failure-only observation, endpoint-return advice, no auto retry/fallback, identity privacy and closed-session rejection.');
